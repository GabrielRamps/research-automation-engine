import jsPDF from 'jspdf';

interface ResearchSession {
  id: string;
  business_name: string;
  industry: string;
  location: string;
  services?: string;
  target_audience?: string;
  project_type: string;
  phase1_raw?: any;
  phase1_summary?: any;
  phase2_raw?: any;
  phase2_summary?: any;
  phase3_raw?: any;
  phase3_summary?: any;
  phase4_synthesis?: any;
  phase5_blueprint?: any;
  total_generation_time?: number;
  api_costs?: any;
  created_at: string;
}

/**
 * Generate Master Research Report PDF
 */
export async function generateMasterReportPDF(session: ResearchSession): Promise<Blob> {
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  const margin = 20;
  const maxWidth = pageWidth - (margin * 2);
  let yPosition = margin;

  // Helper function to add text with word wrap
  const addText = (text: string, fontSize: number = 10, isBold: boolean = false) => {
    pdf.setFontSize(fontSize);
    pdf.setFont('helvetica', isBold ? 'bold' : 'normal');
    
    const lines = pdf.splitTextToSize(text, maxWidth);
    
    for (const line of lines) {
      if (yPosition > pageHeight - margin) {
        pdf.addPage();
        yPosition = margin;
      }
      pdf.text(line, margin, yPosition);
      yPosition += fontSize * 0.5;
    }
    yPosition += 5; // Add spacing after paragraph
  };

  const addHeading = (text: string, level: number = 1) => {
    const fontSize = level === 1 ? 18 : level === 2 ? 14 : 12;
    yPosition += 10; // Extra space before heading
    addText(text, fontSize, true);
  };

  const addPageBreak = () => {
    pdf.addPage();
    yPosition = margin;
  };

  // COVER PAGE
  pdf.setFillColor(59, 130, 246); // Blue
  pdf.rect(0, 0, pageWidth, 80, 'F');
  
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(32);
  pdf.setFont('helvetica', 'bold');
  pdf.text(session.business_name, pageWidth / 2, 40, { align: 'center' });
  
  pdf.setFontSize(18);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Industry Research Report', pageWidth / 2, 55, { align: 'center' });
  
  pdf.setTextColor(0, 0, 0);
  yPosition = 100;
  
  addText(`Industry: ${session.industry}`, 12);
  addText(`Location: ${session.location}`, 12);
  addText(`Project Type: ${session.project_type}`, 12);
  addText(`Generated: ${new Date(session.created_at).toLocaleDateString()}`, 12);
  
  if (session.total_generation_time) {
    const minutes = Math.floor(session.total_generation_time / 60000);
    addText(`Generation Time: ${minutes} minutes`, 12);
  }

  addPageBreak();

  // EXECUTIVE SUMMARY
  addHeading('Executive Summary', 1);
  addText(
    `This comprehensive research report was generated for ${session.business_name}, ` +
    `a ${session.industry} business in ${session.location}. The research covers five critical phases: ` +
    `local competitive intelligence, keyword and search intent analysis, industry benchmarks, ` +
    `strategic synthesis, and implementation blueprint with actionable Cursor prompts.`
  );

  addPageBreak();

  // PHASE 1: LOCAL COMPETITIVE INTELLIGENCE
  addHeading('Phase 1: Local Competitive Intelligence', 1);
  
  if (session.phase1_summary?.content) {
    addHeading('Summary', 2);
    addText(session.phase1_summary.content);
  }

  addPageBreak();

  // PHASE 2: KEYWORD RESEARCH
  addHeading('Phase 2: Keyword & Search Intent Research', 1);
  
  if (session.phase2_summary?.content) {
    addHeading('Summary', 2);
    addText(session.phase2_summary.content);
  }

  addPageBreak();

  // PHASE 3: INDUSTRY INTELLIGENCE
  addHeading('Phase 3: Industry Intelligence & Benchmarks', 1);
  
  if (session.phase3_summary?.content) {
    addHeading('Summary', 2);
    addText(session.phase3_summary.content);
  }

  addPageBreak();

  // PHASE 4: STRATEGIC SYNTHESIS
  addHeading('Phase 4: Strategic Synthesis', 1);
  
  // Backwards compatibility: check final_synthesis.content first, then fall back to content field
  const synthesisContent = session.phase4_synthesis?.final_synthesis?.content || 
                           session.phase4_synthesis?.content || '';
  
  if (synthesisContent) {
    addText(synthesisContent);
  }

  addPageBreak();

  // PHASE 5: IMPLEMENTATION BLUEPRINT
  addHeading('Phase 5: Implementation Blueprint', 1);
  
  if (session.phase5_blueprint?.content) {
    addText(session.phase5_blueprint.content);
  }

  // FOOTER ON EACH PAGE
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(128, 128, 128);
    pdf.text(
      `Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 10,
      { align: 'center' }
    );
    pdf.text(
      'Generated by Research Automation Engine',
      pageWidth / 2,
      pageHeight - 5,
      { align: 'center' }
    );
  }

  return pdf.output('blob');
}

