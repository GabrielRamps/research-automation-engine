/**
 * Parse checklist from Phase 4 synthesis content
 */
function parseChecklistFromSynthesis(content: string): string[] {
  const checklistMatch = content.match(/## IMPLEMENTATION CHECKLIST\s+([\s\S]*?)(?=##|$)/i);
  if (!checklistMatch) {
    return []; // Return empty if no checklist found
  }
  
  const checklistSection = checklistMatch[1];
  const lines = checklistSection.split('\n');
  const items: string[] = [];
  
  for (const line of lines) {
    const trimmed = line.trim();
    // Match checkbox formats: - [ ], [], -, •, or numbered lists
    if (trimmed && (
      trimmed.startsWith('- [ ]') || 
      trimmed.startsWith('[ ]') || 
      trimmed.startsWith('- ') || 
      trimmed.startsWith('• ') ||
      /^\d+\./.test(trimmed)
    )) {
      // Clean up the checkbox/bullet syntax
      const cleaned = trimmed
        .replace(/^-?\s*\[?\s*\]?\s*/, '')
        .replace(/^\d+\.\s*/, '')
        .replace(/^•\s*/, '')
        .trim();
      if (cleaned) {
        items.push(cleaned);
      }
    }
  }
  
  return items;
}

/**
 * Generate Quick Reference Checklist PDF (research-based)
 */
export async function generateChecklistPDF(session: ResearchSession): Promise<Blob> {
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 20;
  let yPosition = margin;

  // Title
  pdf.setFillColor(59, 130, 246);
  pdf.rect(0, 0, pageWidth, 40, 'F');
  
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(24);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Implementation Checklist', pageWidth / 2, 25, { align: 'center' });
  
  pdf.setTextColor(0, 0, 0);
  yPosition = 50;

  // Business Info
  pdf.setFontSize(12);
  pdf.setFont('helvetica', 'bold');
  pdf.text(`${session.business_name}`, margin, yPosition);
  yPosition += 7;
  
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(10);
  pdf.text(`${session.industry} • ${session.location}`, margin, yPosition);
  yPosition += 15;

  // Checklist items with pagination
  const addCheckbox = (text: string) => {
    const pageHeight = pdf.internal.pageSize.getHeight();
    
    // Check if we need a new page
    if (yPosition > pageHeight - margin - 10) {
      pdf.addPage();
      yPosition = margin;
    }
    
    pdf.rect(margin, yPosition - 3, 4, 4);
    pdf.text(text, margin + 7, yPosition);
    yPosition += 7;
  };

  // Helper to add section heading with pagination
  const addSectionHeading = (heading: string) => {
    const pageHeight = pdf.internal.pageSize.getHeight();
    
    yPosition += 10;
    
    // Check if heading needs a new page
    if (yPosition > pageHeight - margin - 20) {
      pdf.addPage();
      yPosition = margin;
    }
    
    pdf.setFontSize(14);
    pdf.setFont('helvetica', 'bold');
    pdf.text(heading, margin, yPosition);
    yPosition += 10;
    
    pdf.setFontSize(10);
    pdf.setFont('helvetica', 'normal');
  };

  // Try to parse checklist from Phase 4 synthesis
  // Backwards compatibility: check final_synthesis.content first, then fall back to content field
  const synthesisContent = session.phase4_synthesis?.final_synthesis?.content || 
                           session.phase4_synthesis?.content || '';
  const checklistItems = parseChecklistFromSynthesis(synthesisContent);
  
  if (checklistItems.length > 0) {
    // Use research-based checklist
    addSectionHeading('Research-Based Implementation Checklist');
    checklistItems.forEach(item => addCheckbox(item));
  } else {
    // Fallback to generic checklist if parsing failed
    addSectionHeading('Must-Have Elements');
    
    addCheckbox('Homepage with hero section and clear value proposition');
    addCheckbox('Service pages for each offering');
    addCheckbox('Contact page with optimized form');
    addCheckbox('Mobile-responsive design');
    addCheckbox('Click-to-call button (mobile)');
    addCheckbox('Trust signals (reviews, certifications, guarantees)');
    addCheckbox('SEO meta titles and descriptions');
    addCheckbox('Schema markup (LocalBusiness, Service)');
    addCheckbox('Google Analytics integration');
    addCheckbox('Page load speed under 3 seconds');
    
    addSectionHeading('Content Requirements');
    
    addCheckbox('Target primary keywords on relevant pages');
    addCheckbox('FAQ page with top 20 questions');
    addCheckbox('About page with company story');
    addCheckbox('Blog posts for top 10 topics');
    addCheckbox('Testimonials and social proof');
    
    addSectionHeading('Technical SEO');
    
    addCheckbox('Sitemap.xml generated');
    addCheckbox('Robots.txt configured');
    addCheckbox('Canonical URLs set');
    addCheckbox('Open Graph tags added');
    addCheckbox('Image alt text optimized');
    
    addSectionHeading('Post-Launch Tests');
    
    addCheckbox('Test all forms and CTAs');
    addCheckbox('Verify mobile experience');
    addCheckbox('Check page load speeds');
    addCheckbox('Test all internal links');
    addCheckbox('Verify tracking and analytics');
  }

  // Footer
  pdf.setFontSize(8);
  pdf.setTextColor(128, 128, 128);
  pdf.text(
    'Generated by Research Automation Engine',
    pageWidth / 2,
    pdf.internal.pageSize.getHeight() - 10,
    { align: 'center' }
  );

  return pdf.output('blob');
}

