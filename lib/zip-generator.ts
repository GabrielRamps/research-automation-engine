import JSZip from 'jszip';

interface ResearchSession {
  business_name: string;
  industry: string;
  location: string;
  phase4_synthesis?: any;
  phase5_blueprint?: any;
}

/**
 * Parse Cursor prompts from Phase 5 blueprint
 */
function parsePromptsFromBlueprint(blueprintContent: string): string[] {
  const prompts: string[] = [];
  
  // Try to extract prompts using regex patterns
  // Looking for sections like "CURSOR PROMPT 1", "PROMPT 1:", etc.
  const promptPatterns = [
    /CURSOR PROMPT (\d+)[:\s-]+([^`]*?)```([^`]+)```/gs,
    /PROMPT (\d+)[:\s-]+([^`]*?)```([^`]+)```/gs,
    /##\s*SECTION\s*(\d+)[:\s-]+CURSOR PROMPT[^`]*?```([^`]+)```/gs
  ];

  let foundPrompts = false;
  
  for (const pattern of promptPatterns) {
    const matches = [...blueprintContent.matchAll(pattern)];
    if (matches.length > 0) {
      foundPrompts = true;
      for (const match of matches) {
        const promptContent = match[match.length - 1]; // Last capture group is the content
        prompts.push(promptContent.trim());
      }
      break;
    }
  }

  // If no prompts found with patterns, try to split by sections
  if (!foundPrompts) {
    const sections = blueprintContent.split(/SECTION \d+:|CURSOR PROMPT \d+:/i);
    for (let i = 1; i < Math.min(sections.length, 7); i++) {
      const section = sections[i];
      const codeBlockMatch = section.match(/```[\s\S]*?```/);
      if (codeBlockMatch) {
        const content = codeBlockMatch[0].replace(/```\w*\n?/g, '').trim();
        prompts.push(content);
      }
    }
  }

  // Return prompts (typically 5 in the new system, 6 in the old system)
  // If we couldn't extract any prompts, throw an error
  if (prompts.length === 0) {
    throw new Error('No prompts found in blueprint. The research may not have completed properly.');
  }

  return prompts;
}

/**
 * Generate ZIP file with 6 Cursor prompts
 */
export async function generateCursorPromptsZip(session: ResearchSession): Promise<Blob> {
  const zip = new JSZip();
  
  // Check both phase4_synthesis (new 4-phase system) and phase5_blueprint (old 5-phase system)
  const blueprintContent = session.phase4_synthesis?.content || 
                           session.phase5_blueprint?.content || 
                           '';
  
  if (!blueprintContent) {
    throw new Error('Blueprint content not found. Make sure the research has completed successfully.');
  }

  // Parse prompts from blueprint
  const prompts = parsePromptsFromBlueprint(blueprintContent);

  // Prompt titles (support both 5 and 6 prompt formats)
  const promptTitles = [
    '01_project_setup_architecture',
    '02_homepage_build',
    '03_service_pages',
    '04_contact_page',
    '05_blog_faq_pages',
    '06_seo_technical'
  ].slice(0, prompts.length);

  // Add each prompt as a text file
  prompts.forEach((prompt, index) => {
    const filename = `${promptTitles[index]}.txt`;
    const content = `# Cursor Prompt ${index + 1}
# Business: ${session.business_name}
# Industry: ${session.industry}
# Location: ${session.location}
# Generated by Research Automation Engine

${prompt}

---
Instructions:
1. Copy the entire prompt above
2. Open Cursor AI
3. Paste into Cursor's chat
4. Let Cursor build the component/page
5. Review and refine as needed
`;
    zip.file(filename, content);
  });

  // Add README
  const readme = `# Cursor Prompts for ${session.business_name}

This package contains ${prompts.length} AI-ready prompts for building your ${session.industry} website.

## Files Included:

${prompts.map((_, index) => {
  const titles = [
    'Project Setup & Architecture',
    'Homepage Build',
    'Service Pages',
    'Contact Page',
    'Blog & FAQ Pages',
    'SEO & Technical'
  ];
  const descs = [
    'Initialize project structure, routing, and design system',
    'Build homepage with hero section and conversion elements',
    'Create service page templates with SEO optimization',
    'Build contact page with optimized form and trust signals',
    'Create blog template and FAQ page structure',
    'Implement schema markup, performance, and analytics'
  ];
  return `${index + 1}. **${promptTitles[index]}.txt** - ${titles[index]}\n   ${descs[index]}`;
}).join('\n\n')}

## How to Use:

1. Open each .txt file in order
2. Copy the entire prompt
3. Paste into Cursor AI
4. Let Cursor generate the code
5. Review and customize as needed

## Tips:

- Work through prompts sequentially (1 → ${prompts.length})
- Review each output before moving to next prompt
- Customize generated code to match your brand
- Test thoroughly before deploying

## Support:

Generated by Research Automation Engine
For questions, refer to your full research report.

---
Business: ${session.business_name}
Industry: ${session.industry}
Location: ${session.location}
Generated: ${new Date().toLocaleDateString()}
`;

  zip.file('README.md', readme);

  // Generate ZIP blob
  const blob = await zip.generateAsync({ 
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 }
  });

  return blob;
}

/**
 * Generate ZIP with all reports + project overview + Cursor prompt for Cursor build.
 * Each file can also be downloaded individually from the results page.
 * Supports both basic (4.1-4.5) and enhanced (10.1-10.8) pipelines.
 */
export async function generateAllReportsZip(session: ResearchSession): Promise<Blob> {
  const zip = new JSZip();
  const p4 = session.phase4_synthesis || {};
  const slug = session.business_name.replace(/\s+/g, '-').toLowerCase();
  const header = (title: string) => `# ${title}
# Business: ${session.business_name}
# Industry: ${session.industry}
# Location: ${session.location}
# Generated: ${new Date().toLocaleDateString()}
# Generated by Research Automation Engine

================================================================================
${title.toUpperCase()}
================================================================================

`;

  const isEnhanced = !!(p4.seo_keyword_strategy || p4.competitive_analysis || p4.content_strategy || p4.cro_guide || p4.offpage_roadmap_benchmarks || p4.site_architecture);
  let fileCount = 0;

  if (isEnhanced) {
    const reports: { content: string; file: string; title: string }[] = [
      { content: p4.seo_keyword_strategy?.content || '', file: 'keyword-strategy-prioritization.txt', title: 'Keyword Strategy & Prioritization' },
      { content: p4.competitive_analysis?.content || '', file: 'market-position-competitive-analysis.txt', title: 'Market Position + Competitive Analysis' },
      { content: p4.content_strategy?.content || '', file: 'content-strategy-blog-calendar.txt', title: 'Content Strategy & Blog Calendar' },
      { content: p4.cro_guide?.content || '', file: 'cro-optimization-guide.txt', title: 'CRO Optimization Guide' },
      { content: p4.offpage_roadmap_benchmarks?.content || '', file: 'offpage-roadmap-benchmarks.txt', title: '90-Day Off-Page Roadmap & Benchmarks' },
      { content: p4.site_architecture?.content || '', file: 'site-architecture-seo-specs.txt', title: 'Site Architecture + SEO Specs + Technical SEO' },
      { content: p4.ui_design?.design_system || '', file: 'ui-design-styling-direction.txt', title: 'UI Design & Styling Direction' },
      { content: p4.project_overview?.content || '', file: 'project-overview-for-cursor.txt', title: 'Project Overview for Cursor' },
    ];

    for (const r of reports) {
      if (r.content) {
        zip.file(`${slug}-${r.file}`, header(r.title) + r.content);
        fileCount++;
      }
    }
  } else {
    const reports: { content: string; file: string; title: string }[] = [
      { content: p4.competitive_intelligence?.report || '', file: 'competitive-intelligence-report.txt', title: 'Competitive Intelligence Report' },
      { content: p4.seo_strategy?.guide || '', file: 'seo-content-strategy-guide.txt', title: 'SEO & Content Strategy Guide' },
      { content: p4.cro_optimization?.guide || '', file: 'conversion-optimization-guide.txt', title: 'Conversion Optimization Guide' },
      { content: p4.wireframe?.outline || '', file: 'website-wireframe-outline.txt', title: 'Website Wireframe & Outline' },
      { content: p4.ui_design?.design_system || '', file: 'ui-design-philosophy.txt', title: 'UI & Design Philosophy' },
      { content: p4.project_overview?.content || '', file: 'project-overview-for-cursor.txt', title: 'Project Overview for Cursor' },
    ];

    for (const r of reports) {
      if (r.content) {
        zip.file(`${slug}-${r.file}`, header(r.title) + r.content);
        fileCount++;
      }
    }
  }

  if (fileCount === 0) {
    throw new Error('No report content found. Make sure the research has completed successfully.');
  }

  const readme = isEnhanced
    ? `# Research Package: ${session.business_name}

Industry: ${session.industry}
Location: ${session.location}
Generated: ${new Date().toLocaleDateString()}

## What's in this ZIP

1. **Keyword Strategy & Prioritization** – 3-tier keyword universe, search intent mapping, priority scoring
2. **Market Position + Competitive Analysis** – Market snapshot, per-competitor breakdown with gap analysis
3. **Content Strategy & Blog Calendar** – Topic clusters, PAA/FAQ, location content, 12-month calendar
4. **CRO Optimization Guide** – Trust signals, conversion elements, performance targets
5. **90-Day Off-Page Roadmap & Benchmarks** – GBP/citation/review plan, 30/60/90-day targets
6. **Site Architecture + SEO Specs + Technical SEO** – URL hierarchy, per-page specs, linking map, technical audit
7. **UI Design & Styling Direction** – Design archetype, color palette, typography, first principles
8. **Project Overview for Cursor** – Concise summary for AI builder: what to build and how to use the guides

## How to build your site in Cursor

1. Create or open your project in Cursor.
2. Attach all report files and the **Project Overview** (e.g. add to project or @ mention in chat).
3. Build the site page by page using the strategy, architecture, and design direction.

Generated by Research Automation Engine
`
    : `# Research Package: ${session.business_name}

Industry: ${session.industry}
Location: ${session.location}
Generated: ${new Date().toLocaleDateString()}

## What's in this ZIP

- **Competitive Intelligence Report** – Market positioning and competitor analysis
- **SEO & Content Strategy Guide** – Keywords, content roadmap, local SEO
- **Conversion Optimization Guide** – CTAs, trust signals, form optimization
- **Website Wireframe & Outline** – Site structure and page list
- **UI & Design Philosophy** – Design principles and color palette (no rigid specs)
- **Project Overview for Cursor** – One doc to attach in Cursor: what to build and how to use the guides

## How to build your site in Cursor

1. Create or open your project in Cursor.
2. Attach the report files and the **Project Overview** (e.g. add to project or @ mention in chat).
3. Build the site page by page using the strategy and design philosophy—adapt spacing and layout to each page.

Generated by Research Automation Engine
`;

  zip.file('README.txt', readme);

  const blob = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 }
  });

  return blob;
}

