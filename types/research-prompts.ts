/**
 * TypeScript types for Research Prompts System
 */

export interface ResearchPrompt {
  id: string;
  phase: 1 | 2 | 3;
  order_index: number;
  name: string;
  prompt_template: string;
  internal_notes?: string | null;
  status: 'active' | 'disabled';
  override_max_results?: number | null;
  created_at: string;
  updated_at: string;
  created_by?: string;
}

export interface GlobalTavilyConfig {
  search_depth: 'basic' | 'advanced';
  max_results: number;
  include_raw_content: boolean;
  include_answer: boolean;
  include_images: boolean;
  time_range?: 'd' | 'w' | 'm' | 'y' | '';
}

export interface PromptTestRequest {
  promptTemplate: string;
  testData: {
    industry: string;
    location: string;
    services: string;
    target_audience: string;
    search_radius: string;
  };
}

export interface PromptTestResponse {
  query: string;
  sources: Array<{
    url: string;
    title: string;
    content: string;
    score: number;
  }>;
}

/**
 * Phase 4 Prompt Interface
 * Represents a configurable Claude prompt for Phase 4 sub-phases
 */
export interface Phase4Prompt {
  id: string;
  subphase: string; // Dynamic subphases (4.1 - 4.99)
  order_index: number;
  name: string;
  prompt_template: string;
  internal_notes?: string | null;
  status: 'active' | 'disabled';
  created_at: string;
  updated_at: string;
  created_by?: string;
}

/**
 * Phase 4 Synthesis State Interface
 * Represents the state of Phase 4 multi-stage synthesis
 */
export interface Phase4SynthesisState {
  status: 'starting' | 'phase4_1' | 'phase4_2' | 'phase4_3' | 'phase4_4' | 'phase4_5' | 'phase4_6' | 'phase4_7' | 'complete' | string;
  progress: string;
  current_subphase: string | null; // Dynamic subphases (4.1 - 4.99)
  competitive_intelligence?: SubPhaseResult;
  seo_strategy?: SubPhaseResult;
  cro_optimization?: SubPhaseResult;
  wireframe?: WireframeResult;
  ui_design?: UIDesignResult;
  all_copy?: CopyResult; // Backwards compatibility
  page_prompts?: PagePromptsResult;
  final_synthesis?: FinalSynthesisResult; // Backwards compatibility
  content?: string; // Backwards compatibility
}

/**
 * Sub-phase Result Interface
 * Represents the output of sub-phases 4.1, 4.2, and 4.3
 */
export interface SubPhaseResult {
  thinking: string;
  report?: string; // For 4.1
  guide?: string;  // For 4.2 and 4.3
  timestamp: string;
}

/**
 * Wireframe Result Interface
 * Represents the output of sub-phase 4.4 (Wireframe/Outline)
 */
export interface WireframeResult {
  thinking: string;
  outline: string;
  timestamp: string;
}

/**
 * UI Design Result Interface
 * Represents the output of sub-phase 4.5 (UI Design & Color Palette)
 */
export interface UIDesignResult {
  thinking: string;
  design_system: string;
  timestamp: string;
}

/**
 * Copy Result Interface
 * Represents the output of sub-phase 4.6 (Copy for All Pages)
 * DEPRECATED: Page copy is no longer generated by the pipeline.
 */
export interface CopyResult {
  thinking: string;
  copy_content: string;
  timestamp: string;
}

/**
 * Page Prompts Result Interface
 * Represents the output of sub-phases 4.N+ (Individual Page Prompts)
 */
export interface PagePromptsResult {
  [pageName: string]: {
    thinking: string;
    prompt: string;
    timestamp: string;
  };
}

/**
 * Final Synthesis Result Interface
 * Represents the output of sub-phase 4.4 (OLD SYSTEM - for backwards compatibility)
 */
export interface FinalSynthesisResult {
  thinking: string;
  content: string;
  prompts_and_blueprint: boolean;
  citations: any[];
  timestamp: string;
}
